export const fromOfficialPlan = (x: number, y: number): MapPoint => ({
  x: Number((x * 0.6 - 60).toFixed(1)),
  y: Number((y * 0.6 - 10).toFixed(1)),
});
type XY = readonly [number, number];

// Smooth traced control points without changing their registration.
export function trace(points: readonly XY[], closed = false): string {
  const p = points.map(([x, y]) => fromOfficialPlan(x, y));
  if (p.length < 2) return "";
  const n = p.length;
  let result = `M${p[0]!.x} ${p[0]!.y}`;
  for (let i = 0; i < (closed ? n : n - 1); i++) {
    const a = p[closed ? (i + n - 1) % n : Math.max(0, i - 1)]!;
    const b = p[i]!;
    const c = p[(i + 1) % n]!;
    const d = p[closed ? (i + 2) % n : Math.min(n - 1, i + 2)]!;
    result += `C${b.x + (c.x - a.x) / 6} ${b.y + (c.y - a.y) / 6} ${c.x - (d.x - b.x) / 6} ${c.y - (d.y - b.y) / 6} ${c.x} ${c.y}`;
  }
  return result + (closed ? "Z" : "");
}

